/**
 * Represents the final result of the image processing pipeline.
 *
 * @property originalBitmap The original source image as loaded.
 * @property maskBitmap The binary segmentation mask generated by YOLO.
 * @property inpaintedBitmap The final car-free result (null if processing failed).
 * @property isServerProcessed True if the high-quality SDXL backend was used.
 * @property errorMessage Error description if the pipeline failed.
 */
data class PipelineResult(
    val originalBitmap: Bitmap,
    val maskBitmap: Bitmap,
    val inpaintedBitmap: Bitmap?,
    val isServerProcessed: Boolean = false,
    val errorMessage: String? = null
)

/**
 * Orchestrates the full image processing workflow:
 * 1. Image loading and preprocessing (via [ImageProcessor])
 * 2. Object detection and mask generation (via [YoloService])
 * 3. Neural inpainting (via [InpaintingEngine] or [ServerSdxlApi])
 */
class StaticImagePipeline(
    private val imageProcessor: ImagePreprocessingService,
    private val yoloService: YoloService,
    private val miGanInference: InpaintingEngine,
    private val serverSdxlApi: ServerInpainter
) {
    /**
     * True if the underlying YOLO neural engine has been initialized and is ready for inference.
     */
    val isInitialized: Boolean
        get() = yoloService.isInitialized
    
    /**
     * Initializes the YOLO model weights and the on-device MI-GAN inpainting session.
     */
    suspend fun initialize() = withContext(Dispatchers.Default) {
        val modelName = "yolo11s"
        AppLogger.info("StaticImagePipeline initializing with model: $modelName")

        yoloService.initialize(modelName = modelName, useFP16 = false)
        miGanInference.initialize()
    }

    /**
     * Runs the complete pipeline on a single image URI:
     * loads image, runs YOLO segmentation, and performs inpainting.
     *
     * @param uri URI of the input image
     * @param downscaleMp Optional downscale limit in megapixels
     * @param maskUpscale Scale factor for mask boundary dilation
     * @param scoreThreshold Confidence threshold for vehicle detection
     * @param useServerSdxl True to use remote SDXL, false for on-device MI-GAN
     * @param onMaskGenerated Optional callback receiving the intermediate mask Bitmap
     * @param onProgressUpdate Optional progress reporter callback
     */
    suspend fun processImage(
        uri: Uri,
        downscaleMp: Float?,
        maskUpscale: Float,
        scoreThreshold: Float,
        useServerSdxl: Boolean,
        onMaskGenerated: ((Bitmap) -> Unit)? = null,
        onProgressUpdate: ((stage: String, percent: Int) -> Unit)? = null
    ): PipelineResult = withContext(Dispatchers.Default) {
        if (!isInitialized) {
            AppLogger.info("StaticImagePipeline processImage called on uninitialized pipeline; auto-initializing now...")
            onProgressUpdate?.invoke("Initializing Neural Engines", 10)
            initialize()
        }

        var processedImage: ImageProcessor.ProcessedImage? = null
        var maskMat: Mat? = null
        try {
            // 1. Process Input
            onProgressUpdate?.invoke("Loading & Preprocessing Image", 25)
            processedImage = imageProcessor.processInputImage(
                imageUri = uri,
                modelWidth = 640,
                modelHeight = 640,
                downscaleMp = downscaleMp
            )
            
            // 2. YOLO Mask Generation
            onProgressUpdate?.invoke("Running YOLO Segmentation", 50)
            val config = YoloConfig(scoreThreshold = scoreThreshold)
            val yoloResult = yoloService.inferDetailed(
                transformedMat = processedImage.transformedMat,
                xRatio = processedImage.xRatio,
                yRatio = processedImage.yRatio,
                upscaleFactor = maskUpscale,
                originalWidth = processedImage.originalMat.cols(),
                originalHeight = processedImage.originalMat.rows(),
                overrideConfig = config
            )
            maskMat = yoloResult.mask
            
            // Generate Mask Bitmap for UI
            val maskBitmap = Bitmap.createBitmap(
                maskMat.cols(),
                maskMat.rows(),
                Bitmap.Config.ARGB_8888
            )
            Utils.matToBitmap(maskMat, maskBitmap)
            onMaskGenerated?.invoke(maskBitmap)

            // 3. Neural Inpainting
            onProgressUpdate?.invoke(if (useServerSdxl) "Running Cloud SDXL Inpainting" else "Running On-Device Inpainting", 75)
            val inpaintedBitmap = if (useServerSdxl) {
                serverSdxlApi.processWithSdxl(
                    originalBitmap = processedImage.originalBitmap,
                    maskBitmap = maskBitmap,
                    previewBitmap = processedImage.transformedBitmap
                )
            } else {
                val inpaintMat = miGanInference.inpaint(
                    imageMat = processedImage.originalMat,
                    maskMat = maskMat
                )
                val outBmp = MatScaler.createDisplayBitmap(inpaintMat)
                inpaintMat.release()
                outBmp
            }
            
            onProgressUpdate?.invoke("Completed", 100)
            return@withContext PipelineResult(
                originalBitmap = processedImage.originalBitmap,
                maskBitmap = maskBitmap,
                inpaintedBitmap = inpaintedBitmap,
                isServerProcessed = useServerSdxl
            )
            
        } catch (e: Exception) {
            AppLogger.error("StaticImagePipeline Error", e)
            return@withContext PipelineResult(
                originalBitmap = processedImage?.originalBitmap ?: createBitmap(1, 1),
                maskBitmap = createBitmap(1, 1),
                inpaintedBitmap = null,
                errorMessage = e.message
            )
        } finally {
            processedImage?.release()
            maskMat?.release()
        }
    }
    
    /**
     * Releases model sessions and closes open resources.
     */
    fun close() {
        yoloService.close()
        miGanInference.close()
    }
}
